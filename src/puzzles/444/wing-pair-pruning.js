import { assertValidState, solvedState } from "./state.js";
import { extractWingState } from "./wings.js";
import { deriveCentreNeutralCommutators } from "./centre-neutral-macros.js";

export const WING_PAIR_COORDINATE_SIZE = 276; // C(24, 2)

function pairCode(first, second) {
  const a = Math.min(first, second);
  const b = Math.max(first, second);
  return a * 24 + b;
}

function decodePairCode(code) {
  return [Math.floor(code / 24), code % 24];
}

const GOAL_SLOTS_BY_SIGNATURE = (() => {
  const bySignature = new Map();
  const solvedWings = extractWingState(solvedState());

  for (let slot = 0; slot < solvedWings.length; slot++) {
    const signature = solvedWings[slot].signature;
    if (!bySignature.has(signature)) bySignature.set(signature, []);
    bySignature.get(signature).push(slot);
  }

  for (const [signature, slots] of bySignature) {
    if (slots.length !== 2) {
      throw new Error(`Expected two solved wing slots for ${signature}`);
    }
    bySignature.set(signature, Object.freeze([...slots].sort((a, b) => a - b)));
  }

  return bySignature;
})();

function buildPairingMoves() {
  const byPermutation = new Map();

  for (const macro of deriveCentreNeutralCommutators()) {
    const direct = [...macro.wingDestinationBySource];
    const inverse = Array(direct.length);
    direct.forEach((destination, source) => {
      inverse[destination] = source;
    });

    byPermutation.set(direct.join(","), Object.freeze(direct));
    byPermutation.set(inverse.join(","), Object.freeze(inverse));
  }

  return Object.freeze([...byPermutation.values()]);
}

const PAIRING_MOVES = buildPairingMoves();
const TABLES = new Map();

export function getWingPairSignatures() {
  return Object.freeze([...GOAL_SLOTS_BY_SIGNATURE.keys()]);
}

/** Return the two current wing-slot indices for one edge-colour signature. */
export function encodeWingPairPosition(state, signature) {
  assertValidState(state);
  if (!GOAL_SLOTS_BY_SIGNATURE.has(signature)) {
    throw new RangeError(`Unknown wing-pair signature: ${signature}`);
  }

  const wings = extractWingState(state);
  const positions = [];
  for (let slot = 0; slot < wings.length; slot++) {
    if (wings[slot].signature === signature) positions.push(slot);
  }

  if (positions.length !== 2) {
    throw new RangeError(
      `Expected exactly two ${signature} wings; found ${positions.length}`
    );
  }
  return Object.freeze(positions.sort((a, b) => a - b));
}

/**
 * Build an exact pair-position pattern database over verified centre-neutral
 * macro permutations. The table may cover only the orbit generated by those
 * macros; unreachable pair coordinates remain marked as unvisited.
 */
export function buildWingPairPruningTable(signature) {
  const goal = GOAL_SLOTS_BY_SIGNATURE.get(signature);
  if (!goal) throw new RangeError(`Unknown wing-pair signature: ${signature}`);

  const cached = TABLES.get(signature);
  if (cached) {
    return {
      signature,
      coordinateCount: cached.visited,
      maxDistance: cached.maxDistance,
      cached: true
    };
  }

  const distances = new Uint8Array(24 * 24);
  distances.fill(0xff);
  const queue = new Uint16Array(WING_PAIR_COORDINATE_SIZE);
  const start = pairCode(goal[0], goal[1]);
  distances[start] = 0;
  queue[0] = start;

  let head = 0;
  let tail = 1;
  let maxDistance = 0;

  while (head < tail) {
    const code = queue[head++];
    const [a, b] = decodePairCode(code);
    const nextDistance = distances[code] + 1;

    for (const destination of PAIRING_MOVES) {
      const next = pairCode(destination[a], destination[b]);
      if (distances[next] !== 0xff) continue;
      if (tail >= queue.length) {
        throw new Error("Wing-pair BFS exceeded the 276-state coordinate size");
      }

      distances[next] = nextDistance;
      queue[tail++] = next;
      if (nextDistance > maxDistance) maxDistance = nextDistance;
    }
  }

  const table = { distances, visited: tail, maxDistance };
  TABLES.set(signature, table);
  return {
    signature,
    coordinateCount: tail,
    maxDistance,
    cached: false
  };
}

export function getWingPairDistance(position, signature) {
  if (
    !Array.isArray(position) ||
    position.length !== 2 ||
    position.some((slot) => !Number.isInteger(slot) || slot < 0 || slot >= 24) ||
    position[0] === position[1]
  ) {
    throw new RangeError("Expected two distinct wing-slot indices in 0..23");
  }

  buildWingPairPruningTable(signature);
  const code = pairCode(position[0], position[1]);
  const distance = TABLES.get(signature).distances[code];
  if (distance === 0xff) {
    throw new RangeError(
      `Wing-pair coordinate for ${signature} is outside the centre-neutral macro orbit`
    );
  }
  return distance;
}

/** Maximum exact single-pair distance; an admissible macro-depth lower bound. */
export function estimateWingPairingMacroDepth(state) {
  assertValidState(state);
  let bound = 0;

  for (const signature of GOAL_SLOTS_BY_SIGNATURE.keys()) {
    const position = encodeWingPairPosition(state, signature);
    bound = Math.max(bound, getWingPairDistance(position, signature));
  }

  return bound;
}
